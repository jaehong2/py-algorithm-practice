"""
문제: 회문수 탐색
카테고리: 배열
풀이: 7×7 격자판에서 5자리 회문수 개수 구하기

7×7 격자판에서 가로/세로 방향으로 연속된 5자리 숫자가
회문수인 경우의 수를 구한다.

회문수: 앞에서 읽으나 뒤에서 읽으나 같은 수 (예: 12321)

탐색 범위:
- 가로: 각 행에서 연속 5칸 (시작점 0~2, 총 3개)
- 세로: 각 열에서 연속 5칸 (시작점 0~2, 총 3개)

입력: 7줄에 걸쳐 7개의 숫자 (1~9)
출력: 회문수의 개수

입력예제:
2 3 5 3 2 1 2
1 2 3 4 5 6 7
2 3 5 3 2 1 2
1 2 3 4 5 6 7
2 3 5 3 2 1 2
1 2 3 4 5 6 7
2 3 5 3 2 1 2

출력예제:
25
"""

a = [list(map(int, input().split())) for _ in range(7)]
cnt = 0
for i in range(7):
    for j in range(3):
        row = a[i][j:j+5]
        
        if row == row[::-1]:
            cnt += 1
                  
        col = [a[j+k][i] for k in range(5)]
        if col == col[::-1]:
            cnt += 1      
print(cnt)
            
      
                  


            

